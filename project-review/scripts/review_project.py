def is_emoji(ch: str) -> bool:
    cp = ord(ch)
    return any(lo <= cp <= hi for lo, hi in EMOJI_RANGES)


def iter_entries(base: Path):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for fn in filenames:
            yield Path(dirpath) / fn


def in_releases(f: Path, root: Path) -> bool:
    parts = f.relative_to(root).parts
    return len(parts) >= 2 and parts[0] == "docs" and parts[1] == "releases"


def run_git(repo: Path, *args: str) -> tuple[int, str]:
    try:
        p = subprocess.run(["git", "-c", "core.quotepath=false", *args], cwd=repo,
                           capture_output=True, text=True, encoding="utf-8", errors="replace")
    except FileNotFoundError:
        return 127, "git 不可用"
    return p.returncode, (p.stdout + p.stderr).strip()


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")



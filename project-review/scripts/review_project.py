def is_software(root: Path) -> bool:
    code = root / "code"
    return code.is_dir() and any(f.suffix.lower() in CODE_EXTS for f in iter_entries(code))


def parse_progress_rows(root: Path) -> list[dict]:
    prog = root / "docs" / "开发进度.md"
    rows: list[dict] = []
    if not prog.exists():
        return rows
    section = ""
    for i, ln in enumerate(read_text(prog).splitlines(), 1):
        s = ln.strip()
        if s.startswith("## "):
            section = s[3:].strip()
            continue
        if "功能进度" not in section or not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if len(cells) < 4 or all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
            continue
        name, status, doccell = cells[1], cells[2], cells[3]
        if name in ("", "功能点"):
            continue
        rows.append({"line": i, "name": name, "status": status, "doc": doccell})
    return rows


def section_table_rows(text: str, heading_no: str) -> list[str]:
    rows, inside = [], False
    for ln in text.splitlines():
        s = ln.strip()
        if s.startswith("## "):
            inside = s.startswith(f"## {heading_no}")
            continue
        if inside and s.startswith("|"):
            cells = [c.strip() for c in s.strip("|").split("|")]
            if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
                rows.append(s)
    return rows


def check_features(root: Path) -> None:
    for row in parse_progress_rows(root):
        if row["status"] in PROGRESS_TODO:
            continue
        expected = row["doc"] if row["doc"] not in ("", "—", "-") else f"docs/features/{row['name']}.md"
        target = root / expected
        if not target.exists():
            add("W", "A", "功能文档缺失", "docs/开发进度.md",
                f"功能「{row['name']}」状态为「{row['status']}」，但缺少 {expected}", 8, row["line"])
            continue
        if target.suffix != ".md":
            continue
        ftext = read_text(target)
        m = re.search(r"^\s*-\s*\*{0,2}状态\*{0,2}[：:]\s*([^\s（(*]+)", ftext, re.M)
        if not m:
            add("W", "A", "功能文档缺状态", expected, "应有「- 状态：」字段", 5)
            continue
        doc_status = m.group(1).strip().strip("*")
        if doc_status not in KNOWN_STATUS:
            add("W", "A", "功能文档状态异常", expected, f"「{doc_status}」不在标准状态集内", 5)
        elif doc_status != row["status"]:
            add("E", "A", "状态不一致", expected,
                f"台账为「{row['status']}」、功能文档为「{doc_status}」，审核门禁依据冲突", 15)
        if doc_status in ("测试通过", "已审核"):
            test_rows = [r for r in section_table_rows(ftext, "3") if not r.startswith("| #")]
            if not test_rows or not any("通过" in r for r in test_rows):
                add("E", "A", "测试记录缺失", expected,
                    f"功能标记「{doc_status}」但「测试情况」表无任何「通过」记录", 15)
            if doc_status == "已审核":
                audit_rows = [r for r in section_table_rows(ftext, "4") if not r.startswith("| 日期")]
                if not audit_rows:
                    add("E", "A", "审核记录缺失", expected,
                        "功能标记「已审核」但「审核记录」表为空——审核门禁要求人工确认留痕", 15)



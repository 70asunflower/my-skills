# ---------- C/D 维: git 审查 ----------

def audit_git(root: Path, n_commits: int) -> None:
    stats = {"total": 0, "bad": 0, "big": 0, "missed_log": 0, "dirty": 0,
             "untracked": 0, "stale_days": -1}
    audit_git.stats = stats
    if not (root / ".git").is_dir():
        add("E", "D", "未纳入git", "", "项目不是 git 仓库，无法追溯历史", 50)
        return
    rc, log = run_git(root, "log", f"-n{n_commits}", "--date=short",
                      "--pretty=format:%h%x09%ad%x09%s")
    if rc != 0 or not log.strip():
        add("W", "D", "无提交历史", "", "git 仓库尚无任何提交", 10)
        return
    commits = [l.split("\t", 2) for l in log.splitlines() if l.strip()]
    stats["total"] = len(commits)

    # 项目停滞
    try:
        last_day = datetime.strptime(commits[0][1], "%Y-%m-%d").date()
        stats["stale_days"] = (datetime.now().date() - last_day).days
        if stats["stale_days"] > 30:
            add("I", "D", "项目停滞", "", f"最近一次提交已在 {stats['stale_days']} 天前", 0)
    except (ValueError, IndexError):
        pass

    # commit 消息合规
    for h, date, subject in commits:
        if MSG_RE.match(subject) or subject.startswith(("Merge ", "Revert ")) \
                or subject == "Initial commit":
            continue
        reason = "空泛消息" if VAGUE_MSG.match(subject) else "缺少语义化前缀(feat:/fix:/docs:/…)"
        add("W", "D", "commit消息不规范", "", f"{h}「{subject}」——{reason}", 3)
        stats["bad"] += 1

    # 提交粒度
    for h, date, subject in commits:
        _, names = run_git(root, "show", "--name-only", "--pretty=format:", h)
        if len([n for n in names.splitlines() if n.strip()]) > 30:
            stats["big"] += 1
    if stats["big"]:
        add("W", "D", "大杂烩提交", "", f"{stats['big']} 次提交单次改动超过 30 个文件，建议按逻辑拆分",
            3 * stats["big"])

    # 修改留痕联动 + 日志日期异常
    today = datetime.now().date()
    docs = root / "docs"
    if docs.is_dir():
        for f in iter_entries(docs):
            if f.name.startswith(".") or in_releases(f, root):
                continue
            if not f.name.endswith(".md") or f.name.endswith(".log.md"):
                continue
            logf = f.parent / (f.stem + ".log.md")
            if not logf.exists():
                continue
            entry_dates = re.findall(r"^##\s*(\d{4}-\d{2}-\d{2})", read_text(logf), re.M)
            if not entry_dates:
                continue
            rel = f.relative_to(root).as_posix()
            try:
                if any(datetime.strptime(d, "%Y-%m-%d").date() > today for d in entry_dates):
                    add("W", "C", "日志日期异常", rel, "日志条目日期在未来（时钟错误或补记），请核对", 3)
            except ValueError:
                pass
            rc2, last = run_git(root, "log", "-1", "--date=short",
                                "--pretty=format:%h%x09%ad%x09%s", "--", rel)
            if rc2 != 0 or not last.strip():
                continue
            h, date, subject = (last.split("\t", 2) + ["", "", ""])[:3]
            newest = max(entry_dates)
            if date > newest:
                add("E", "C", "修改未留痕", rel,
                    f"最后提交 {h}「{subject}」在 {date}，但日志最后条目为 {newest}", 8)
                stats["missed_log"] += 1

    # 入库卫生: .env/密钥文件、大文件
    rc3, tracked = run_git(root, "ls-files")
    if rc3 == 0:
        tracked_names = [t for t in tracked.splitlines() if t.strip()]
        risky = [t for t in tracked_names
                 if Path(t).name == ".env" or t.lower().endswith((".pem", ".key", ".p12", ".pfx"))]
        for t in risky[:3]:
            add("W", "D", "密钥文件入库", t, "口令/证书文件不应入库，应移出并加 .gitignore", 5)
        for t in tracked_names:
            p = root / t
            try:
                if p.is_file() and p.stat().st_size > 30_000_000:
                    add("W", "D", "大文件入库", t,
                        f"约 {p.stat().st_size // 1_000_000} MB 已入库，仓库膨胀；大数据应放 tmp/ 或外部存储", 4)
            except OSError:
                continue

    _, tracked_tmp = run_git(root, "ls-files", "tmp/")
    if tracked_tmp.strip():
        add("W", "D", "tmp被git跟踪", "tmp/", "tmp/ 应被 .gitignore 忽略", 4)
    _, status = run_git(root, "status", "--porcelain")
    untracked = []
    for line in status.splitlines():
        if line.startswith("?? "):
            p = line[3:].strip().strip('"').replace("\\", "/")
            if not p.startswith("tmp") and not Path(p).name.startswith("."):
                untracked.append(p)
    if untracked:
        shown = ", ".join(untracked[:5]) + ("…" if len(untracked) > 5 else "")
        add("W", "D", "未跟踪正式文件", shown,
            f"共 {len(untracked)} 项，收工前应提交", min(15, 3 * len(untracked)))
        stats["untracked"] = len(untracked)
    stats["dirty"] = sum(1 for l in status.splitlines() if l.strip() and not l.startswith("?? "))
    if stats["dirty"]:
        add("I", "D", "未提交变更", "", f"{stats['dirty']} 项改动待提交", 2)



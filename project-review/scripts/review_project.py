def scan_secrets(root: Path) -> None:
    targets: list[Path] = []
    docs = root / "docs"
    if docs.is_dir():
        targets += [f for f in iter_entries(docs)
                    if f.suffix == ".md" and not f.name.endswith(".log.md")
                    and not f.name.startswith(".") and not in_releases(f, root)]
    code = root / "code"
    if code.is_dir():
        targets += [f for f in iter_entries(code) if f.suffix.lower() in CODE_EXTS]
    for f in targets:
        rel = f.relative_to(root).as_posix()
        for i, ln in enumerate(read_text(f).splitlines(), 1):
            for pat, label in SECRET_E:
                if pat.search(ln):
                    add("E", "E", "疑似密钥泄漏", rel, f"{label}——请立即确认并吊销轮换", 10, i)
            for pat, label in SECRET_W:
                if pat.search(ln):
                    add("W", "E", "敏感信息(需复核)", rel, f"{label}，人工确认是否真实泄露", 5 if "口令" in label else 3, i)


# ---------- F 维: 代码可移植性 ----------

def check_portability(root: Path) -> None:
    code = root / "code"
    if not code.is_dir():
        return
    py_files = [f for f in iter_entries(code) if f.suffix == ".py"]
    third_party: set[str] = set()
    todo_count = 0
    for f in py_files:
        rel = f.relative_to(root).as_posix()
        text = read_text(f)
        if HARDCODED_PATH.search(text):
            add("W", "F", "硬编码路径", rel, "存在 C:/Users/… 类绝对路径，换机即失效，应改配置或相对路径", 4)
        for i, ln in enumerate(text.splitlines(), 1):
            s = ln.strip()
            if s.startswith(COMMENT_PREFIXES) and re.search(r"\b(?:TODO|FIXME|XXX)\b", s, re.I):
                todo_count += 1
        for m in re.finditer(r"^\s*(?:import|from)\s+(\w+)", text, re.M):
            mod = m.group(1)
            if mod in THIRD_PARTY_HINTS:
                third_party.add(mod)
    if third_party and not any((root / d).exists() for d in DEP_FILES):
        add("W", "F", "缺依赖清单", "code/", f"代码使用第三方库（{', '.join(sorted(third_party)[:5])}）但无 requirements.txt / pyproject.toml", 6)
    if todo_count >= 10:
        add("I", "F", "TODO债务", "code/", f"{todo_count} 处 TODO/FIXME 未清，建议登记进开发进度台账", 0)



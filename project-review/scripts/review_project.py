def score() -> tuple[float, str, dict, dict]:
    dim_deduct: dict[str, dict[str, int]] = {d: defaultdict(int) for d in DIMS}
    for f in findings:
        if f["deduct"]:
            dim_deduct[f["dim"]][f["kind"]] += f["deduct"]
    dim_score = {d: max(0, 100 - sum(dim_deduct[d].values())) for d in DIMS}
    total = sum(dim_score[d] * w for d, (_, w) in DIMS.items()) / 100.0
    grade = "A" if total >= 90 else "B" if total >= 75 else "C" if total >= 60 else "D"
    return round(total, 1), grade, dim_score, dim_deduct


def build_report(root: Path, total: float, grade: str, dim_score: dict, dim_deduct: dict) -> str:
    n = {lv: sum(1 for f in findings if f["level"] == lv) for lv in "EWI"}
    verdict = {
        "A": "规范执行良好，仅需处理零星问题。",
        "B": "整体规范，存在须修复的缺口，按问题清单处理。",
        "C": "规范执行有明显漏洞，须集中整改后再继续开发。",
        "D": "规范基本失控，建议对照 AGENTS.md 全面整改。",
    }[grade]
    lines = [
        "# 项目审查报告", "",
        f"- 项目：{root.name}",
        f"- 审查时间：{datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"- 审查工具：project-review v{VERSION}",
        f"- 规范基准：{SPEC_BASE}", "",
        "## 总评", "",
        f"**{total}/100（{grade} 级）**——{n['E']} 项必须修复、{n['W']} 项建议修复、{n['I']} 项提示。{verdict}", "",
        "## 评分明细", "",
        "| 维度 | 权重 | 得分 | 扣分明细 |",
        "|------|------|------|----------|",
    ]
    for d, (name, w) in DIMS.items():
        detail = "；".join(f"{k} -{v}" for k, v in sorted(dim_deduct[d].items(), key=lambda x: -x[1])) or "无"
        lines.append(f"| {d} {name} | {w}% | {dim_score[d]} | {detail} |")
    lines += ["", "## 问题清单", ""]
    icon = {"E": "必须修复", "W": "建议修复", "I": "提示"}
    for lv in "EWI":
        items = [f for f in findings if f["level"] == lv]
        lines.append(f"### {lv} 级·{icon[lv]}（{len(items)}）")
        if not items:
            lines.append("（无）")
        for f in items:
            loc = f"{f['file']}:{f['line']}" if f["line"] else f["file"]
            lines.append(f"- [{f['dim']}·{f['kind']}] {loc} — {f['detail']}")
        lines.append("")
    st = audit_git.stats
    lines += ["## git 审查", ""]
    if st:
        ok = st["total"] - st["bad"]
        lines += [
            f"- 提交消息合规率：{ok}/{st['total']}（违规 {st['bad']} 条）",
            f"- 修改未留痕：{st['missed_log']} 处（git 记录了文档修改，日志无对应条目）",
            f"- 工作区：{st['dirty']} 项未提交，{st['untracked']} 项未跟踪正式文件",
            f"- 大杂烩提交（>30 文件）：{st['big']} 次",
        ]
        if st["stale_days"] >= 0:
            lines.append(f"- 最近提交距今：{st['stale_days']} 天")
        lines.append("")
    else:
        lines += ["- 本项目未纳入 git，无历史可审。", ""]
    lines += ["## 修复优先级", ""]
    pri = [f for f in findings if f["level"] == "E"] + [f for f in findings if f["level"] == "W"]
    if not pri:
        lines.append("1. 无须修复，保持现状。")
    else:
        act_map = {
            "状态不一致": "与用户核对真实状态，统一台账与功能文档并记日志",
            "测试记录缺失": "补做验收测试并把用例与结果写入功能文档测试表",
            "审核记录缺失": "提交人工审核，通过后回填审核记录表",
            "修改未留痕": "按第 3 节格式在对应 .log.md 补记该次修改",
            "文档AI痕迹": "改写为正式书面表达，删除对话腔与 AI 声明",
            "版本副本增殖": "确认保留版本后合并回主文件，git rm 副本并记日志",
            "缺规范目录": "运行 project-init 初始化补齐目录",
            "未纳入git": "git init 并完成首次规范提交",
            "疑似密钥泄漏": "确认后立即吊销并轮换密钥，从历史中清除（git filter-repo）",
            "密钥文件入库": "移出口令文件、加入 .gitignore，必要时轮换",
            "缺依赖清单": "按实际 import 生成 requirements.txt（pip freeze 或手写）",
            "硬编码路径": "改为相对路径或配置项",
            "存放错位": "按 AGENTS.md 第 1 节移入正确目录并 git mv、记日志",
            "内容完全重复": "保留一份，另一份删除并在日志记录去向",
        }
        for i, f in enumerate(pri[:12], 1):
            act = act_map.get(f["kind"], "按 AGENTS.md 对应条款整改并在日志中记录")
            lines.append(f"{i}. **{f['kind']}**（{f['file']}）——{act}")
        if len(pri) > 12:
            lines.append(f"…（其余 {len(pri) - 12} 项见问题清单）")
    return "\n".join(lines) + "\n"


def find_projects(base: Path, depth: int) -> list[Path]:
    found: list[Path] = []
    bp = len(base.parts)

    def walk(cur: Path) -> None:
        if (cur / "AGENTS.md").exists():
            found.append(cur)
            return
        if len(cur.parts) - bp >= depth:
            return
        for e in sorted(cur.iterdir()):
            if e.is_dir() and e.name not in SKIP_DIRS and not e.name.startswith("."):
                walk(e)

    walk(base)
    return found


def review(root: Path, n_commits: int) -> None:
    findings.clear()
    audit_git.stats = {}
    check_structure(root)
    docs = root / "docs"
    if docs.is_dir():
        for f in iter_entries(docs):
            if f.name.startswith(".") or in_releases(f, root):
                continue
            if f.name.endswith(".log.md"):
                continue
            if f.suffix == ".md":
                scan_markdown(f, root)
    scan_names(root)
    scan_duplicates(root)
    check_releases(root)
    check_docs_quality(root)
    scan_logs(root)
    scan_code_comments(root)
    scan_secrets(root)
    check_portability(root)
    check_sw_structure(root)
    audit_git(root, n_commits)


def write_report(root: Path, report: str, out: str) -> None:
    outp = (root / out).resolve()
    outp.parent.mkdir(parents=True, exist_ok=True)
    outp.write_text(report, encoding="utf-8", newline="\n")
    print(f"[报告] 已写入 {outp}")
    log = outp.parent / (outp.stem + ".log.md")
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    entry = (f"## {now} — 创建\n- 修改者：project-review\n"
             f"- 摘要：生成项目审查报告\n- 原因：阶段性规范审查\n")
    if log.exists():
        with log.open("a", encoding="utf-8", newline="\n") as fh:
            fh.write("\n" + entry)
        print(f"[报告] 日志已追加 {log.name}")
    else:
        log.write_text(entry, encoding="utf-8", newline="\n")
        print(f"[报告] 日志已创建 {log.name}")


def main() -> int:
    ap = argparse.ArgumentParser(description="project-review 项目规范审查（六维评分 + 报告）")
    ap.add_argument("target", nargs="?", default=".", help="项目目录（--scan 时为工作区根）")
    ap.add_argument("--out", help="报告写入路径（相对项目根，建议 docs/审查报告.md）")
    ap.add_argument("--commits", type=int, default=50, help="纳入 git 审查的最近提交数（默认 50）")
    ap.add_argument("--json", action="store_true", help="JSON 输出")
    ap.add_argument("--scan", action="store_true", help="批量审查工作区内所有含 AGENTS.md 的项目")
    ap.add_argument("--depth", type=int, default=2, help="--scan 搜索深度（默认 2）")
    args = ap.parse_args()

    root = Path(args.target).expanduser().resolve()
    if not root.exists():
        print(f"[错误] 目录不存在: {root}")
        return 1

    if args.scan:
        projects = find_projects(root, max(0, args.depth))
        if not projects:
            print("未发现含 AGENTS.md 的项目")
            return 0
        any_e = False
        print(f"{'评分':>6}  {'等级':^4}  {'E':>2} {'W':>3} {'I':>2}  项目")
        for p in projects:
            review(p, args.commits)
            total, grade, _, _ = score()
            n = {lv: sum(1 for f in findings if f["level"] == lv) for lv in "EWI"}
            any_e = any_e or n["E"] > 0
            print(f"{total:>6}  {grade:^4}  {n['E']:>2} {n['W']:>3} {n['I']:>2}  {p}")
        print("\n对单个项目运行可查看完整报告（--out docs/审查报告.md 落盘）")
        return 1 if any_e else 0

    review(root, args.commits)
    total, grade, dim_score, dim_deduct = score()
    report = build_report(root, total, grade, dim_score, dim_deduct)
    if args.json:
        print(json.dumps({"project": str(root), "score": total, "grade": grade,
                          "dims": {f"{d} {n}": dim_score[d] for d, (n, _) in DIMS.items()},
                          "findings": findings}, ensure_ascii=False, indent=2))
    else:
        print(report)
    if args.out:
        write_report(root, report, args.out)
    return 1 if any(f["level"] == "E" for f in findings) else 0


if __name__ == "__main__":
    sys.exit(main())
